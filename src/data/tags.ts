// Как показывать теги из Obsidian на сайте. В Obsidian в тегах нельзя пробел,
// поэтому многословные теги пишутся через дефис; здесь — их нормальный вид.
// Теги, где дефис правильный («Дизайн-система»), сюда не добавлять.
const labels: Record<string, string> = {
  'Внутренний-инструмент': 'Внутренний инструмент',
};

export const tagLabel = (tag: string) => labels[tag] ?? tag;
