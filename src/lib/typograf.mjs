/*
  Висячие предлоги и союзы: короткое слово («в», «и», «на», «для», «при»…)
  приклеивается неразрывным пробелом к следующему, а тире — к предыдущему слову.
  Так в конце строки не остаётся одинокой буквы или тире в начале строки.
*/
const NBSP = '\u00A0';
// Слова до двух букв и частые трёхбуквенные предлоги и союзы
const SHORT_WORD =
  /(?<=^|[\s\u00A0(«„"])([\p{L}\d]{1,2}|для|без|под|над|при|про|или|что|как|это|все|уже|так|еще|ещё) (?=\S)/giu;
const DASH = / (—|–)/g;

export const typograf = (text) => text.replace(SHORT_WORD, `$1${NBSP}`).replace(DASH, `${NBSP}$1`);

// Последнее слово абзаца приклеено к предпоследнему — одно слово не уходит на новую строку
export const noWidow = (text) => text.replace(/ (\S+)$/, '\u00A0$1');
